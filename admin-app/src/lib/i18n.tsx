export const catalog: Record<Loc, Record<string, string>> = { en, ta };

function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    k in params ? String(params[k]) : `{${k}}`,
  );
}

export type TFn = (key: string, fallback: string, params?: TParams) => string;

interface I18nState {
  locale: Loc;
  setLocale: (code: Loc) => void;
  t: TFn;
}

const I18nContext = createContext<I18nState | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Loc>('en');

  useEffect(() => {
    void AsyncStorage.getItem(STORAGE_KEY).then((saved) => {
      if (saved === 'en' || saved === 'ta') setLocaleState(saved);
    });
  }, []);

  const value = useMemo<I18nState>(() => {
    const t: TFn = (key, fallback, params) =>
      interpolate(catalog[locale][key] ?? fallback, params);
    return {
      locale,
      setLocale: (code: Loc) => {
        setLocaleState(code);
        void AsyncStorage.setItem(STORAGE_KEY, code);
      },
      t,
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>');
  return ctx;
}

export function useT(): TFn {
  return useI18n().t;
}
